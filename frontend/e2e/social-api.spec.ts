import {test, expect} from '@playwright/test'

test('real API persists likes, follows and comment counts across reload', async ({page,request},info)=>{
 const email=`social-${info.project.name}-${Date.now()}@example.test`, password='TestPassword123!'
 const registered=await request.post('/api/auth/register',{data:{email,login:'Social Test',hashpassword:password}})
 expect(registered.ok()).toBeTruthy()
 const login=await request.post('/api/auth/login',{data:{email,password}})
 expect(login.ok()).toBeTruthy()
 const {accesToken}=await login.json()
 await page.addInitScript(token=>localStorage.setItem('token',token),accesToken)
 await page.goto('/')
 const card=page.locator('article').filter({has:page.getByRole('heading',{name:'Synthetic demo',exact:true})})
 const like=card.getByRole('button',{name:'Нравится',exact:true})
 await expect(like).toHaveAttribute('aria-pressed','false')
 const originalLikes=Number(await like.textContent())
 await like.click()
 await expect(like).toHaveAttribute('aria-pressed','true')
 await expect(like).toHaveText(String(originalLikes+1))
 await card.getByRole('button',{name:'Подписаться',exact:true}).click()
 await expect(card.getByRole('button',{name:'Отписаться',exact:true})).toBeVisible()
 const comments=card.getByRole('button',{name:'Комментарии',exact:true})
 const originalComments=Number(await comments.textContent())
 await comments.click()
 const content=`Synthetic social comment ${info.project.name} ${Date.now()}`
 await card.getByLabel('Ваш комментарий').fill(content)
 await card.getByRole('button',{name:'Отправить комментарий'}).click()
 await expect(card.getByText(content,{exact:true})).toBeVisible()
 await expect(comments).toHaveText(String(originalComments+1))
 await page.reload()
 await expect(like).toHaveAttribute('aria-pressed','true')
 await expect(like).toHaveText(String(originalLikes+1))
 await expect(comments).toHaveText(String(originalComments+1))
 await card.getByRole('button',{name:'Отписаться',exact:true}).click()
 await expect(card.getByRole('button',{name:'Подписаться',exact:true})).toBeVisible()
 await like.click()
 await expect(like).toHaveAttribute('aria-pressed','false')
 await expect(like).toHaveText(String(originalLikes))
})
